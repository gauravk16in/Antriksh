export default function PixelIcon({ name, size = 28 }) {
  const rows = ICONS[name] || [];
  let d = '';
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) {
      d += `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`;
    }
  });
  return (
    <svg className="pixel-icon" viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true">
      <path fill="currentColor" d={d} />
    </svg>
  );
}